def _raw_transcript_refs(
    *,
    run_dir: Path,
    candidate_id: str,
    kernel_id: str,
    materialized_rows: Sequence[Mapping[str, Any]],
) -> list[Dict[str, Any]]:
    refs: list[Dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    for row in materialized_rows:
        path = Path(str(row.get("path", "")))
        stage_id = str(row.get("stage_id", ""))
        if not path.exists() or not path.is_file() or not stage_id:
            continue
        try:
            rel = str(path.resolve().relative_to(Path(run_dir).resolve()))
        except ValueError:
            rel = str(path)
        key = (stage_id, rel)
        if key in seen:
            continue
        seen.add(key)
        refs.append(
            {
                "stage_id": stage_id,
                "candidate_id": candidate_id,
                "kernel_id": kernel_id,
                "path": rel,
                "sha256": sha256_file(path),
                "hash_algorithm": "sha256",
                "candidate_specific": True,
                "shared_microkernel_smoke_only": False,
                "source_role": "fresh_candidate_specific_raw_stage_evidence",
            }
        )
    return refs


