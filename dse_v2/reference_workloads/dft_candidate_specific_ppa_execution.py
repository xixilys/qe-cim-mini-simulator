#!/usr/bin/env python3
"""Fresh candidate-specific PPA execution lane for DFT/QE hardware closure.

The provenance audit deliberately rejects raw hard-gate files that were copied
or wrapped from an older source-flow directory.  This module consumes the
tie-breaker queue and executes selected candidate/kernel units into their
canonical ``candidate_specific_evidence`` directories, recording the actual
commands and IC/EDA tool-version probes that were attempted.

The lane is still fail-closed: it may create fresh raw evidence/provenance, but
it never marks hardware completion, deliverable completion, or a trusted
winner.  Existing parser/adjudicator/release-gate stages must still consume the
raw files and decide pass/fail.
"""

