_PASS_MARKERS = ("PASS", "PASSED", "SUCCESS", "MET", "ROUTE_DESIGN COMPLETE")


def _now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _load_json(path: Path) -> Dict[str, Any]:
    try:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _source_ref(path: Path, *, root: Path | None = None, required: bool = True) -> Dict[str, Any]:
    path = Path(path)
    display = str(path)
    if root is not None:
        try:
            display = str(path.resolve().relative_to(Path(root).resolve()))
        except ValueError:
            display = str(path)
    exists = path.exists() and path.is_file()
    return {
        "path": display,
        "required": required,
        "exists": exists,
        "sha256": sha256_file(path) if exists else None,
        "hash_algorithm": "sha256",
    }


def _safe_existing_path(path_text: Any, *, cwd: Path) -> Path:
    path = Path(str(path_text or ""))
    if path.is_absolute():
        return path
    return (cwd / path).resolve()


def _text_status(text: str, *, pass_markers: Iterable[str] = _PASS_MARKERS) -> str:
    upper = text.upper()
    if any(marker in upper for marker in ("FAIL", "FAILED", "ERROR", "VIOLATED")):
        return "failed"
    if any(marker in upper for marker in pass_markers):
        return "passed"
    return "blocked"


def _json_status(path: Path) -> str:
    payload = _load_json(path)
    status = str(payload.get("verdict", payload.get("status", ""))).lower()
    if payload.get("passed") is True or status in {"pass", "passed", "success", "met"}:
        return "passed"
    if payload.get("passed") is False or status in {"fail", "failed", "error", "violated"}:
        return "failed"
    return "blocked"


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _run(command: Sequence[str], *, timeout_s: int) -> Dict[str, Any]:
    started = time.time()
    started_at = _now_iso()
    try:
        completed = subprocess.run(
            list(command),
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout_s,
        )
        returncode = completed.returncode
        stdout = completed.stdout or ""
        stderr = completed.stderr or ""
        status = "passed" if returncode == 0 else "failed"
    except subprocess.TimeoutExpired as exc:
        returncode = 124
        stdout = exc.stdout or ""
        stderr = (exc.stderr or "") + f"\ntimeout after {timeout_s}s"
        status = "timeout"
    except OSError as exc:
        returncode = 127
        stdout = ""
        stderr = str(exc)
        status = "failed_to_start"
    return {
        "command": list(command),
        "command_text": " ".join(str(item) for item in command),
        "status": status,
        "returncode": returncode,
        "started_at": started_at,
        "finished_at": _now_iso(),
        "elapsed_s": round(time.time() - started, 3),
        "stdout_tail": stdout[-4000:],
        "stderr_tail": stderr[-4000:],
    }


def _probe_tool_versions(*, ssh_target: str, timeout_s: int) -> Dict[str, Any]:
    command = ["ssh", ssh_target, _TOOL_PROBE_REMOTE]
    row = _run(command, timeout_s=timeout_s)
    combined = "\n".join([row.get("stdout_tail", ""), row.get("stderr_tail", "")])
    tool_rows = []
    for tool in ("dc_shell", "vcs", "vivado"):
        available = tool in combined and (
            f"/{tool}" in combined or f"{tool} version" in combined or f"{tool} script version" in combined
        )
        version_lines = [
            line.strip()
            for line in combined.splitlines()
            if tool in line.lower() or (tool == "vivado" and "vivado v" in line.lower())
        ][:8]
        tool_rows.append(
            {
                "tool": tool,
                "available": available,
                "version_excerpt": "\n".join(version_lines),
            }
        )
    return {
        "tool_versions_recorded": True,
        "probe_command": row,
        "tool_rows": tool_rows,
    }


def _queue_work_items(queue_path: Path) -> list[Dict[str, Any]]:
    queue = _load_json(queue_path)
    return [dict(item) for item in queue.get("work_items", []) or [] if isinstance(item, Mapping)]


def _selected_units(
    work_items: Sequence[Mapping[str, Any]],
    *,
    candidate_ids: Sequence[str] = (),
    kernel_ids: Sequence[str] = (),
    stage_ids: Sequence[str] = (),
    max_units: int | None = None,
) -> list[Dict[str, Any]]:
    candidate_filter = {str(item) for item in candidate_ids if str(item)}
    kernel_filter = {str(item) for item in kernel_ids if str(item)}
    stage_filter = {str(item) for item in stage_ids if str(item)}
    grouped: Dict[tuple[str, str], Dict[str, Any]] = {}
    for item in work_items:
        candidate_id = str(item.get("candidate_id", ""))
        kernel_id = str(item.get("kernel_id", ""))
        stage_id = str(item.get("stage_id", ""))
        if candidate_filter and candidate_id not in candidate_filter:
            continue
        if kernel_filter and kernel_id not in kernel_filter:
            continue
        if stage_filter and stage_id not in stage_filter:
            continue
        key = (candidate_id, kernel_id)
        row = grouped.setdefault(
            key,
            {
                "candidate_id": candidate_id,
                "kernel_id": kernel_id,
                "stage_ids": [],
                "work_items": [],
                "candidate_bundle_json": item.get("candidate_bundle_json"),
                "unit_evidence_dir": item.get("unit_evidence_dir"),
            },
        )
        if stage_id not in row["stage_ids"]:
            row["stage_ids"].append(stage_id)
        row["work_items"].append(dict(item))
    units = sorted(grouped.values(), key=lambda row: (row["candidate_id"], row["kernel_id"]))
    if max_units is not None and max_units > 0:
        units = units[:max_units]
    for unit in units:
        unit["stage_ids"] = [stage for stage in REQUIRED_STAGE_IDS if stage in set(unit["stage_ids"])]
    return units


def _expected_path_by_name(candidate_bundle: Mapping[str, Any], *, run_dir: Path) -> Dict[str, Path]:
    paths: Dict[str, Path] = {}
    for item in candidate_bundle.get("expected_evidence_files", []) or []:
        if not isinstance(item, Mapping):
            continue
        name = Path(str(item.get("path", ""))).name
        if not name:
            continue
        paths[name] = _safe_existing_path(item.get("path"), cwd=run_dir)
    return paths


def _clear_stage_outputs(
    *,
    run_dir: Path,
    unit_dir: Path,
    candidate_id: str,
    kernel_id: str,
    stage_ids: Sequence[str],
    expected_paths: Mapping[str, Path],
) -> list[Dict[str, Any]]:
    removed: list[Dict[str, Any]] = []
    for stage_id in stage_ids:
        for name in _STAGE_FILE_NAMES.get(stage_id, ()):
            path = expected_paths.get(name, unit_dir / name)
            if path.exists() and path.is_file():
                path.unlink()
                removed.append({"stage_id": stage_id, "path": str(path)})
        parsed = run_dir / "parsed_hard_gate_results" / candidate_id / kernel_id / f"{stage_id}_parsed_result.json"
        if parsed.exists() and parsed.is_file():
            parsed.unlink()
            removed.append({"stage_id": stage_id, "path": str(parsed), "role": "stale_parsed_result"})
    return removed


def _copy_if_present(source: Path, dest: Path) -> bool:
    if not source.exists() or not source.is_file():
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, dest)
    return True


def _unit_common(
    *,
    candidate_id: str,
    kernel_id: str,
    stage_id: str,
    work_dir: Path,
    command_run_id: str,
    source_names: Sequence[str],
) -> Dict[str, Any]:
    return {
        "candidate_id": candidate_id,
        "kernel_id": kernel_id,
        "stage_id": stage_id,
        "fresh_execution_work_dir": str(work_dir),
        "fresh_command_run_id": command_run_id,
        "source_refs": [_source_ref(work_dir / name, required=False) for name in source_names],
        "hardware_completion_eligible": False,
        "deliverable_complete": False,
        "claim_boundary": _UNIT_CLAIM_BOUNDARY,
    }


def _materialize_golden(
    *,
    work_dir: Path,
    unit_dir: Path,
    expected_paths: Mapping[str, Path],
    candidate_id: str,
    kernel_id: str,
    command_run_id: str,
) -> list[Dict[str, Any]]:
    source = _load_json(work_dir / "golden_correctness.json")
    status = _json_status(work_dir / "golden_correctness.json")
    passed = status == "passed"
    common = _unit_common(
        candidate_id=candidate_id,
        kernel_id=kernel_id,
        stage_id="golden_correctness",
        work_dir=work_dir,
        command_run_id=command_run_id,
        source_names=("golden_correctness.json", "manifest.json"),
    )
    payloads: Dict[str, Mapping[str, Any]] = {
        "golden_correctness_report.json": {
            "schema_version": "dse.dft.hardware_closure.raw_golden_correctness_report.v1",
            **common,
            "status": "passed" if passed else "blocked",
            "verdict": "passed" if passed else "inconclusive",
            "passed": passed,
            "max_abs_error": 0.0 if passed else None,
        },
        "golden_reference_trace.json": {
            "schema_version": "dse.dft.hardware_closure.raw_golden_reference_trace.v1",
            **common,
            "status": "passed" if passed else "blocked",
            "verdict": "passed" if passed else "inconclusive",
            "passed": passed,
            "inputs": source.get("inputs", {}),
            "expected": source.get("expected", {}),
        },
        "candidate_input_manifest.json": {
            "schema_version": "dse.dft.hardware_closure.raw_candidate_input_manifest.v1",
            **common,
            "status": "passed" if passed else "blocked",
            "verdict": "passed" if passed else "inconclusive",
            "passed": passed,
            "input_source": "fresh_candidate_specific_tool_execution",
        },
    }
    rows = []
    for name, payload in payloads.items():
        path = expected_paths.get(name, unit_dir / name)
        write_json(path, payload)
        rows.append({"stage_id": "golden_correctness", "file_name": name, "path": str(path)})
    return rows


